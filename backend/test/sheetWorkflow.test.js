/**
 * Evaluates a single atomic SQL condition generated by buildParameterizedSelectQuery
 * against an in-memory product row.
 */
function evaluateConditionClause(clauseSql, row, params) {
  const trimmed = clauseSql.trim();

  // 1. Nested size.<KEY> integer comparison:
  const sizeKeyMatch = trimmed.match(
    /\(size::jsonb\s*->>\s*'([A-Za-z0-9]+)'\)[\s\S]+?,\s*0\)\s*(=|<>|>=|<=|>|<)\s*\$(\d+)/i
  );
  if (sizeKeyMatch) {
    const sizeKey = sizeKeyMatch[1];
    const op = sizeKeyMatch[2];
    const targetVal = Number(params[Number(sizeKeyMatch[3]) - 1]);
    let actualVal = 0;
    try {
      const parsed = JSON.parse(row.size || '{}');
      actualVal = Number.isFinite(Number(parsed[sizeKey]))
        ? Number(parsed[sizeKey])
        : 0;
    } catch {
      actualVal = 0;
    }
    return compareNumbers(actualVal, op, targetVal);
  }

  // 2. Virtual total_stock comparison:
  // COALESCE((SELECT SUM(...) FROM jsonb_each_text(...)), 0) <op> $N
  const totalStockMatch = trimmed.match(
    /jsonb_each_text[\s\S]+?,\s*0\)\s*(=|<>|>=|<=|>|<)\s*\$(\d+)/i
  );
  if (totalStockMatch) {
    const op = totalStockMatch[1];
    const targetVal = Number(params[Number(totalStockMatch[2]) - 1]);
    const actualVal = computeTotalStockFromSizeJson(row.size);
    return compareNumbers(actualVal, op, targetVal);
  }

  // 3. Boolean comparisons on best
  const boolMatch = trimmed.match(/^best\s*(=|<>)\s*\$(\d+)$/i);
  if (boolMatch) {
    const op = boolMatch[1];
    const val = Boolean(params[Number(boolMatch[2]) - 1]);
    return op === '=' ? Boolean(row.best) === val : Boolean(row.best) !== val;
  }

  // 4. Numeric comparisons on price, discount, ordered
  const numBetweenMatch = trimmed.match(
    /^(price|discount|ordered)\s+BETWEEN\s+\$(\d+)\s+AND\s+\$(\d+)$/i
  );
  if (numBetweenMatch) {
    const col = numBetweenMatch[1].toLowerCase();
    const minVal = Number(params[Number(numBetweenMatch[2]) - 1]);
    const maxVal = Number(params[Number(numBetweenMatch[3]) - 1]);
    return Number(row[col]) >= minVal && Number(row[col]) <= maxVal;
  }

  const numMatch = trimmed.match(
    /^(price|discount|ordered)\s*(=|<>|>=|<=|>|<)\s*\$(\d+)$/i
  );
  if (numMatch) {
    const col = numMatch[1].toLowerCase();
    const op = numMatch[2];
    const val = Number(params[Number(numMatch[3]) - 1]);
    return compareNumbers(Number(row[col]), op, val);
  }

  // 5. Case-insensitive exact string comparisons: LOWER(col) = LOWER($N) or <>
  const lowerEqMatch = trimmed.match(
    /^LOWER\(([a-z_]+)\)\s*(=|<>)\s*LOWER\(\$(\d+)\)$/i
  );
  if (lowerEqMatch) {
    const col = lowerEqMatch[1].toLowerCase();
    const op = lowerEqMatch[2];
    const val = String(params[Number(lowerEqMatch[3]) - 1] ?? '').toLowerCase();
    const actual = String(row[col] ?? '').toLowerCase();
    return op === '=' ? actual === val : actual !== val;
  }

  // 6. ILIKE substring / prefix comparisons: col ILIKE $N
  const ilikeMatch = trimmed.match(/^([a-z_]+)\s+ILIKE\s+\$(\d+)$/i);
  if (ilikeMatch) {
    const col = ilikeMatch[1].toLowerCase();
    const pattern = String(params[Number(ilikeMatch[2]) - 1] ?? '').toLowerCase();
    const actual = String(row[col] ?? '').toLowerCase();
    if (pattern.startsWith('%') && pattern.endsWith('%')) {
      const inner = pattern.slice(1, -1);
      return actual.includes(inner);
    }
    if (pattern.endsWith('%')) {
      const prefix = pattern.slice(0, -1);
      return actual.startsWith(prefix);
    }
    return actual === pattern;
  }

  // 7. Array IN comparison: col = ANY($N::text[]) or col = ANY($N::uuid[])
  const anyMatch = trimmed.match(
    /^([a-z_]+)\s*=\s*ANY\(\$(\d+)::(?:text|uuid)\[\]\)$/i
  );
  if (anyMatch) {
    const col = anyMatch[1].toLowerCase();
    const arr = params[Number(anyMatch[2]) - 1];
    if (!Array.isArray(arr)) return false;
    return arr.some(
      (item) => String(item).toLowerCase() === String(row[col] ?? '').toLowerCase()
    );
  }

  // 8. Relative date comparison
  const relDateMatch = trimmed.match(/INTERVAL\s+'1 day'\s*\*\s*\$(\d+)/i);
  if (relDateMatch) {
    const days = Number(params[Number(relDateMatch[1]) - 1]);
    const cutoff = Date.now() - days * 24 * 60 * 60 * 1000;
    return new Date(row.created_at).getTime() >= cutoff;
  }

  return true;
}

function compareNumbers(actual, op, target) {
  switch (op) {
    case '=':
      return actual === target;
    case '<>':
      return actual !== target;
    case '>':
      return actual > target;
    case '<':
      return actual < target;
    case '>=':
      return actual >= target;
    case '<=':
      return actual <= target;
    default:
      return false;
  }
}

/**
 * Evaluates a single SET assignment expression from UPDATE products SET ... against a row.
 */
function applyAssignmentClause(assignSql, row, params) {
  const trimmed = assignSql.trim();
  if (/^updated_at\s*=\s*NOW\(\)$/i.test(trimmed)) {
    return;
  }

  // 1. CASE id WHEN $3::uuid THEN $4 ... END (for nested size JSON updates)
  if (/^size\s*=\s*CASE\s+id/i.test(trimmed)) {
    const whenMatches = [
      ...trimmed.matchAll(/WHEN\s+\$(\d+)::uuid\s+THEN\s+\$(\d+)/gi),
    ];
    for (const m of whenMatches) {
      const idParam = params[Number(m[1]) - 1];
      const valParam = params[Number(m[2]) - 1];
      if (row.id === idParam) {
        row.size = valParam;
        return;
      }
    }
    return;
  }

  // 2. Percentage arithmetic on price/discount/ordered:
  // e.g. price = ROUND((price * (1 + ($3::numeric / 100.0)))::numeric, 2)
  const pctMatch = trimmed.match(
    /^([a-z_]+)\s*=\s*ROUND\(\(\1\s*\*\s*\(1\s*([+-])\s*\(\$(\d+)::numeric\s*\/\s*100\.0\)\)\)(?:::numeric)?(?:,\s*2)?\)(?:::integer)?$/i
  );
  if (pctMatch) {
    const col = pctMatch[1].toLowerCase();
    const sign = pctMatch[2];
    const pct = Number(params[Number(pctMatch[3]) - 1]);
    const factor = sign === '+' ? 1 + pct / 100 : 1 - pct / 100;
    const raw = Number(row[col]) * factor;
    row[col] = col === 'ordered' ? Math.round(raw) : Math.round(raw * 100) / 100;
    return;
  }

  // 3. Add / subtract / multiply arithmetic on numeric columns:
  // e.g. price = ROUND((price - $3::numeric)::numeric, 2) or ordered = ordered + $3::integer
  const arithMatch = trimmed.match(
    /^([a-z_]+)\s*=\s*(?:ROUND\(\()?\1\s*([+\-*])\s*\$(\d+)(?:::numeric|::integer)?(?:\)(?:::numeric)?(?:,\s*2)?\)(?:::integer)?)?$/i
  );
  if (arithMatch) {
    const col = arithMatch[1].toLowerCase();
    const op = arithMatch[2];
    const operand = Number(params[Number(arithMatch[3]) - 1]);
    const current = Number(row[col]);
    let raw = current;
    if (op === '+') raw = current + operand;
    else if (op === '-') raw = current - operand;
    else if (op === '*') raw = current * operand;
    row[col] = col === 'ordered' ? Math.round(raw) : Math.round(raw * 100) / 100;
    return;
  }

  // 4. Direct scalar assignment: col = $N
  const directMatch = trimmed.match(/^([a-z_]+)\s*=\s*\$(\d+)$/i);
  if (directMatch) {
    const col = directMatch[1].toLowerCase();
    const paramIdx = Number(directMatch[2]) - 1;
    row[col] = params[paramIdx];
  }
}

/**
 * Splits a top-level comma-separated SQL SET list while respecting parentheses.
 */
function splitTopLevelComma(str) {
  const parts = [];
  let depth = 0;
  let current = '';
  for (let i = 0; i < str.length; i += 1) {
    const ch = str[i];
    if (ch === '(') depth += 1;
    else if (ch === ')') depth = Math.max(0, depth - 1);
    if (ch === ',' && depth === 0) {
      parts.push(current.trim());
      current = '';
    } else {
      current += ch;
    }
  }
  if (current.trim()) {
    parts.push(current.trim());
  }
  return parts;
}

/**
 * Splits a SQL WHERE expression on top-level ` AND ` or ` OR ` (outside parentheses).
 */
function splitTopLevelLogical(str, keyword) {
  const parts = [];
  let depth = 0;
  let lastIdx = 0;
  const token = ` ${keyword.toUpperCase()} `;
  const upper = str.toUpperCase();

  for (let i = 0; i < str.length; i += 1) {
    const ch = str[i];
    if (ch === '(') depth += 1;
    else if (ch === ')') depth = Math.max(0, depth - 1);

    if (depth === 0 && upper.startsWith(token, i)) {
      parts.push(str.slice(lastIdx, i).trim());
      i += token.length - 1;
      lastIdx = i + 1;
    }
  }
  if (lastIdx <= str.length) {
    parts.push(str.slice(lastIdx).trim());
  }
  return parts.filter(Boolean);
}

/**
 * Creates an in-memory PostgreSQL simulator supporting the single `products` table
 * (matching products.csv), `businesses`, parameterized queries, compound AND/OR filters,
 * virtual total_stock, nested size.<KEY>, arithmetic updates, and transactions.
 */
function createInMemorySheetPool() {
  const businesses = new Map();
  let products = [];
  let monotonicClock = Date.now();
  let failNextUpdate = false;

  function nextIsoTimestamp() {
    monotonicClock = Math.max(Date.now(), monotonicClock + 1);
    return new Date(monotonicClock).toISOString();
  }

  // Seed default business
  businesses.set('684a8863-5094-4c8b-9b15-c50c06335b7f', {
    id: '684a8863-5094-4c8b-9b15-c50c06335b7f',
    name: 'Veloura Apparel',
    created_at: nextIsoTimestamp(),
  });

  function cloneState() {
    return {
      businesses: new Map(
        Array.from(businesses.entries()).map(([k, v]) => [k, { ...v }])
      ),
      products: products.map((p) => ({ ...p })),
    };
  }

  function restoreState(snap) {
    products = snap.products;
  }

  async function executeQuery(sql, params = []) {
    const rawSql = sql.trim();
    const normalized = rawSql.replace(/\s+/g, ' ').toUpperCase();

    if (normalized === 'SELECT 1;' || normalized === 'SELECT 1') {
      return { rows: [{ '?column?': 1 }], rowCount: 1 };
    }

    // Business lookup
    if (
      normalized.startsWith(
        'SELECT ID, NAME, CREATED_AT FROM BUSINESSES WHERE ID = $1'
      )
    ) {
      const bizId = params[0];
      const biz = businesses.get(bizId);
      if (!biz) return { rows: [], rowCount: 0 };
      return { rows: [{ ...biz }], rowCount: 1 };
    }

    if (normalized.startsWith('INSERT INTO BUSINESSES')) {
      const [id, name] = params;
      const row = {
        id: id || crypto.randomUUID(),
        name,
        created_at: nextIsoTimestamp(),
      };
      businesses.set(row.id, row);
      return { rows: [{ ...row }], rowCount: 1 };
    }

    // Delete existing products for a business
    if (normalized === 'DELETE FROM PRODUCTS WHERE BUSINESS_ID = $1;') {
      const bizId = params[0];
      const beforeCount = products.length;
      products = products.filter((p) => p.business_id !== bizId);
      return { rows: [], rowCount: beforeCount - products.length };
    }

    // Insert Product (supports both CSV import column order and dynamic create columns)
    if (normalized.startsWith('INSERT INTO PRODUCTS')) {
      const colMatch = rawSql.match(/INSERT\s+INTO\s+products\s*\(([^)]+)\)/i);
      const colNames = colMatch
        ? colMatch[1].split(',').map((c) => c.trim().toLowerCase())
        : [
            'business_id',
            'name',
            'category',
            'description',
            'best',
            'color',
            'discount',
            'ordered',
            'images',
            'size',
            'price',
            'created_at',
          ];
      const mapped = {};
      let paramCursor = 0;
      for (const col of colNames) {
        if (
          (col === 'created_at' || col === 'updated_at') &&
          paramCursor >= params.length
        ) {
          continue;
        }
        mapped[col] = params[paramCursor];
        paramCursor += 1;
      }

      const now = nextIsoTimestamp();
      const row = {
        id: crypto.randomUUID(),
        business_id: mapped.business_id,
        name: mapped.name,
        category: mapped.category || null,
        description: mapped.description || null,
        best: Boolean(mapped.best),
        color: mapped.color || null,
        discount: Number(mapped.discount ?? 0),
        ordered: Number.parseInt(mapped.ordered ?? 0, 10),
        images: mapped.images || null,
        size: mapped.size || null,
        price: Number(mapped.price),
        created_at: mapped.created_at
          ? new Date(mapped.created_at).toISOString()
          : now,
        updated_at: now,
      };
      products.push(row);
      return { rows: [{ ...row }], rowCount: 1 };
    }

    // Catalog name + category lookup for productNameResolver
    if (
      normalized.startsWith(
        'SELECT NAME, CATEGORY FROM PRODUCTS WHERE BUSINESS_ID = $1'
      )
    ) {
      const bizId = params[0];
      const rows = products
        .filter((p) => p.business_id === bizId)
        .map((p) => ({ name: p.name, category: p.category ?? null }))
        .sort((a, b) => String(a.name).localeCompare(String(b.name)));
      return { rows, rowCount: rows.length };
    }

    // Context retrieval query on products
    if (
      normalized.startsWith(
        'SELECT ID, BUSINESS_ID, NAME, CATEGORY, DESCRIPTION, BEST, COLOR, DISCOUNT, ORDERED, IMAGES, SIZE, PRICE, CREATED_AT, UPDATED_AT FROM PRODUCTS WHERE BUSINESS_ID = $1'
      )
    ) {
      const bizId = params[0];
      const rows = products
        .filter((p) => p.business_id === bizId)
        .map((p) => ({ ...p }));
      return { rows, rowCount: rows.length };
    }

    // Context retrieval fallback on context_entries
    if (normalized.includes('FROM CONTEXT_ENTRIES WHERE BUSINESS_ID = $1')) {
      return { rows: [], rowCount: 0 };
    }

    // Select Products
    if (normalized.startsWith('SELECT * FROM PRODUCTS')) {
      const bizId = params[0];
      let filtered = products.filter((r) => r.business_id === bizId);

      // Handle SELECT * FROM products WHERE business_id = $1 AND id = ANY($2::uuid[]) FOR UPDATE
      if (Array.isArray(params[1]) && rawSql.includes('ANY($2::uuid[])')) {
        const idSet = new Set(params[1]);
        filtered = filtered.filter((r) => idSet.has(r.id));
        return {
          rows: filtered.map((r) => ({ ...r })),
          rowCount: filtered.length,
        };
      }

      // Extract WHERE body after "WHERE business_id = $1"
      const whereMatch = rawSql.match(
        /WHERE\s+business_id\s*=\s*\$1(?:\s+AND\s+([\s\S]+?))?\s+ORDER\s+BY/i
      );
      const extraWhere = whereMatch && whereMatch[1] ? whereMatch[1].trim() : '';

      if (extraWhere) {
        // Check if it is an OR group: (clause1 OR clause2 ...)
        if (
          extraWhere.startsWith('(') &&
          extraWhere.endsWith(')') &&
          extraWhere.includes(' OR ')
        ) {
          const inner = extraWhere.slice(1, -1);
          const orClauses = splitTopLevelLogical(inner, 'OR');
          filtered = filtered.filter((row) =>
            orClauses.some((c) => evaluateConditionClause(c, row, params))
          );
        } else {
          const andClauses = splitTopLevelLogical(extraWhere, 'AND');
          filtered = filtered.filter((row) =>
            andClauses.every((c) => evaluateConditionClause(c, row, params))
          );
        }
      }

      // Sort
      if (rawSql.includes('ORDER BY price ASC')) {
        filtered.sort((a, b) => a.price - b.price);
      } else if (rawSql.includes('ORDER BY price DESC')) {
        filtered.sort((a, b) => b.price - a.price);
      } else if (rawSql.includes('ORDER BY ordered DESC')) {
        filtered.sort((a, b) => b.ordered - a.ordered);
      } else if (rawSql.includes('ORDER BY discount DESC')) {
        filtered.sort((a, b) => b.discount - a.discount);
      } else {
        filtered.sort(
          (a, b) =>
            new Date(b.created_at).getTime() - new Date(a.created_at).getTime()
        );
      }

      // Limit
      const limitMatch = rawSql.match(/LIMIT\s+\$(\d+)/i);
      if (limitMatch) {
        const limParamIdx = Number(limitMatch[1]) - 1;
        const lim = params[limParamIdx];
        if (Number.isFinite(lim)) {
          filtered = filtered.slice(0, lim);
        }
      }

      return {
        rows: filtered.map((r) => ({ ...r })),
        rowCount: filtered.length,
      };
    }

    // Update Products
    if (normalized.startsWith('UPDATE PRODUCTS')) {
      if (failNextUpdate) {
        failNextUpdate = false;
        throw new Error('Simulated database failure during UPDATE products.');
      }

      const bizId = params[0];
      const targetIds = params[1];

      const setMatch = rawSql.match(/SET\s+([\s\S]+?)\s+WHERE/i);
      const assignments = setMatch ? splitTopLevelComma(setMatch[1]) : [];

      const updated = [];
      for (const row of products) {
        if (row.business_id === bizId && targetIds.includes(row.id)) {
          for (const assign of assignments) {
            applyAssignmentClause(assign, row, params);
          }
          row.updated_at = nextIsoTimestamp();
          updated.push({ ...row });
        }
      }
      return { rows: updated, rowCount: updated.length };
    }

    // Delete Products by IDs
    if (
      normalized.startsWith(
        'DELETE FROM PRODUCTS WHERE BUSINESS_ID = $1 AND ID = ANY'
      )
    ) {
      const bizId = params[0];
      const targetIds = params[1];

      const deleted = [];
      products = products.filter((p) => {
        if (p.business_id === bizId && targetIds.includes(p.id)) {
          deleted.push({ ...p });
          return false;
        }
        return true;
      });
      return { rows: deleted, rowCount: deleted.length };
    }

    throw new Error(`Unsupported SQL in sheet test pool: ${rawSql}`);
  }

  return {
    async query(sql, params) {
      return executeQuery(sql, params);
    },
    async connect() {
      let snapshot = null;
      return {
        async query(sql, params) {
          const cmd = sql.trim().toUpperCase();
          if (cmd === 'BEGIN') {
            snapshot = cloneState();
            return { rows: [], rowCount: 0 };
          }
          if (cmd === 'COMMIT') {
            snapshot = null;
            return { rows: [], rowCount: 0 };
          }
          if (cmd === 'ROLLBACK') {
            if (snapshot) {
              restoreState(snapshot);
              snapshot = null;
            }
            return { rows: [], rowCount: 0 };
          }
          return executeQuery(sql, params);
        },
        release() {},
      };
    },
    async end() {},
    getInternalProducts() {
      return products;
    },
    setFailNextUpdate(flag) {
      failNextUpdate = Boolean(flag);
    },
  };
}

